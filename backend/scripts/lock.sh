#!/usr/bin/env bash
# Freeze backend dependencies (DECISIONS #68). requirements.txt / requirements-dev.txt hold the ranges
# (what Dependabot edits); requirements.lock / requirements-dev.lock hold exact versions with hashes
# (what Docker and CI install). Only releases at least two weeks old are picked.
#   usage: backend/scripts/lock.sh [YYYY-MM-DD]   (default: 14 days ago)
set -euo pipefail
cd "$(dirname "$0")/.."
CUTOFF="${1:-$(python3 -c 'import datetime;print(datetime.date.today()-datetime.timedelta(days=14))')}"
UV="${UV:-uv}"
# Recorded exceptions to the two-week rule (DECISIONS #68): package=newest upload date allowed.
#   anthropic 1.14.0 (2026-10-14): server-side fallbacks + output_config that ai/gateway.py needs.
#   pillow 13.0.0 (2026-10-16), pypdf 6.21.2 (2026-10-21), certifi 2026.10.19: security fixes flagged by pip-audit.
EXCEPTIONS=(--exclude-newer-package "anthropic=2026-10-15T00:00:00Z"
            --exclude-newer-package "pillow=2026-10-17T00:00:00Z"
            --exclude-newer-package "pypdf=2026-10-22T00:00:00Z"
            --exclude-newer-package "certifi=2026-10-21T00:00:00Z")
for pair in "requirements.txt:requirements.lock" "requirements-dev.txt:requirements-dev.lock"; do
  "$UV" pip compile "${pair%%:*}" -o "${pair##*:}" --universal --python-version 3.12 --generate-hashes \
    --exclude-newer "$CUTOFF" "${EXCEPTIONS[@]}" --no-header --quiet
  sed -i.bak "1i\\
# Generated by backend/scripts/lock.sh from ${pair%%:*} (releases up to $CUTOFF). Do not edit by hand.
" "${pair##*:}" && rm -f "${pair##*:}.bak"
done
echo "Locked with releases up to $CUTOFF."
